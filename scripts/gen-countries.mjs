// Generates src/games/flags/data/countries.ts: the 193 UN member states with Dutch and English names.
// Names come from the CLDR data built into Node (Intl.DisplayNames), cleaned up for children.
import { mkdirSync, writeFileSync } from 'node:fs';

const CONTINENTS = {
  europe:
    'AL AD AT BY BE BA BG HR CY CZ DK EE FI FR DE GR HU IS IE IT LV LI LT LU MT MD MC ME NL MK NO PL PT RO RU SM RS SK SI ES SE CH UA GB',
  americas: 'AG AR BS BB BZ BO BR CA CL CO CR CU DM DO EC SV GD GT GY HT HN JM MX NI PA PY PE KN LC VC SR TT US UY VE',
  africa:
    'DZ AO BJ BW BF BI CV CM CF TD KM CG CD CI DJ EG GQ ER SZ ET GA GM GH GN GW KE LS LR LY MG MW ML MR MU MA MZ NA NE NG RW ST SN SC SL SO ZA SS SD TZ TG TN UG ZM ZW',
  asia:
    'AF AM AZ BH BD BT BN KH CN GE IN ID IR IQ IL JP JO KZ KW KG LA LB MY MV MN MM NP KP OM PK PH QA SA SG KR LK SY TJ TH TL TR TM AE UZ VN YE',
  oceania: 'AU FJ KI MH FM NR NZ PW PG WS SB TO TV VU',
};

const EXPECTED = { europe: 44, americas: 35, africa: 54, asia: 46, oceania: 14 };

const OVERRIDES = {
  nl: { CD: 'Democratische Republiek Congo' },
  en: { CD: 'DR Congo', CG: 'Republic of the Congo' },
};

const displayNames = {
  nl: new Intl.DisplayNames(['nl'], { type: 'region' }),
  en: new Intl.DisplayNames(['en-GB'], { type: 'region' }),
};

function clean(name, lang) {
  let out = name.replace(/\s*\(.*\)$/, '');
  if (lang === 'en') out = out.replace(/ & /g, ' and ').replace(/^St\.? /, 'Saint ');
  return out;
}

const rows = [];
for (const [continent, list] of Object.entries(CONTINENTS)) {
  const codes = list.split(' ');
  if (codes.length !== EXPECTED[continent]) {
    throw new Error(`${continent}: expected ${EXPECTED[continent]} codes, got ${codes.length}`);
  }
  for (const code of codes) {
    const row = { code, continent };
    for (const lang of ['nl', 'en']) {
      const raw = displayNames[lang].of(code);
      if (!raw || raw === code) throw new Error(`No ${lang} name for ${code}`);
      row[lang] = OVERRIDES[lang][code] ?? clean(raw, lang);
    }
    rows.push(row);
  }
}
if (new Set(rows.map((r) => r.code)).size !== rows.length) throw new Error('Duplicate country code');
rows.sort((a, b) => a.code.localeCompare(b.code));

const body = rows
  .map((r) => `  { code: '${r.code}', continent: '${r.continent}', nl: ${JSON.stringify(r.nl)}, en: ${JSON.stringify(r.en)} },`)
  .join('\n');

const outDir = new URL('../src/games/flags/data/', import.meta.url);
mkdirSync(outDir, { recursive: true });
writeFileSync(
  new URL('countries.ts', outDir),
  `// Generated by scripts/gen-countries.mjs. Edit the script, not this file.\n` +
    `import type { Country } from '../types';\n\n` +
    `export const COUNTRIES: readonly Country[] = [\n${body}\n];\n`,
);
console.log(`Wrote ${rows.length} countries`);
